/* The CD read and audio layer: cdrom_IsIdle, cdrom_StartRead,
 * cdrom_StartReadAt, cdrom_Pause, cdrom_GetFileSize, cdrom_StartAudio,
 * cdrom_ReadWait, cdrom_LoadExec, and sys_Exec, which runs the executable
 * cdrom_LoadExec reads. .text 0x80036D88 (ROM 0x27588). Start boundary: G8 (the
 * end of 26940.c's -G8 unit). */
#define INCLUDE_ASM_USE_MACRO_INC 1
#include "common.h"
#include "include_asm.h"
#include "bb2.h"

s32 cdrom_IsIdle(void) { return g_cdrom_state.rec.io_state == 0; }

s32 cdrom_StartRead(s32 file_index, s32 dest_addr) {
    s32 file_size;

    if (g_cdrom_state.rec.io_state != 0) {
        return 0;
    }

    g_cdrom_state.rec.file_index = file_index;
    g_cdrom_state.rec.pair = g_cd_file_table[(s16)file_index];
    g_cdrom_state.rec.read_dest_addr = dest_addr;
    g_cdrom_state.rec.stop_request = 0;
    g_cdrom_state.rec.io_state = 2;
    file_size = g_cdrom_state.rec.pair.size;
    g_cdrom_state.rec.unk3E = 0;
    g_cdrom_state.rec.read_sector_count = (u32)(file_size + 0x7FF) >> 11;
    return 1;
}

s32 cdrom_StartReadAt(
    s32 file_index, s32 dest_addr, s32 sector_offset, s32 sector_count) {
    if (cdrom_StartRead(file_index, dest_addr) == 0) {
        return 0;
    }
    CdIntToPos(CdPosToInt(&g_cdrom_state.rec.pair.loc) + sector_offset,
               &g_cdrom_state.rec.pair.loc);
    g_cdrom_state.rec.read_sector_count = sector_count;
    return 1;
}

s32 cdrom_GetFileIndex(s32 file_group, s32 file_index_offset) {
    return g_cdrom_file_group_bases[file_group] + file_index_offset;
}

void cdrom_Pause(void) {
    CdReadyCallback(0);
    cdrom_SetMix(0, 0, 0, 0);
    CdFlush();
    CdControlF(9, 0);
    g_cdrom_state.rec.stop_request = 1;
    g_cdrom_state.rec.io_state = 0xB;
    g_cdrom_state.sync_wait_count = 0;
}

u32 cdrom_GetFileSize(s32 file_index) {
    return g_cd_file_table[file_index].size;
}

void cdrom_WaitIdle(void) {
    u16 *p;
    comb_BeginWait();
    p = &g_cdrom_state.rec.unk3E;
    while (1) {
        if (cdrom_IsIdle() != 0) {
            break;
        }
        comb_ExchangeEmptyPad();
        cdrom_Update();
        if (g_snd_initialized != 0) {
            snd_FlushSoundQueue();
        }
        gpu_DrawDisplayModeOnLocalOtAndSync();
        *p = *p + 2;
        VSync(2);
    }
    comb_EndWait();
}

s32 cdrom_StartAudio(s32 file_index, s32 audio_channel) {
    if (g_cdrom_state.rec.io_state != 0) {
        return 0;
    }

    g_cdrom_state.rec.file_index = file_index;
    g_cdrom_state.rec.pair = g_cd_file_table[g_cdrom_state.rec.file_index];
    g_cdrom_state.rec.audio_end_pos =
        CdPosToInt(&g_cd_file_table[g_cdrom_state.rec.file_index].loc) +
        ((u32)g_cd_file_table[g_cdrom_state.rec.file_index].size >> 11) - 0x96;

    if (audio_channel < 0) {
        g_cdrom_state.rec.is_xa_audio = 0;
        g_cdrom_state.rec.audio_mode = 5;
    } else {
        g_cdrom_state.rec.is_xa_audio = 1;
        g_cdrom_state.file = 1;
        g_cdrom_state.chan = audio_channel;
        CdControlB(0xD, &g_cdrom_state.file, 0);
        g_cdrom_state.rec.audio_mode = 0xC8;
    }

    g_cdrom_state.rec.audio_hold = 0;
    g_cdrom_state.rec.stop_request = 0;
    g_cdrom_state.rec.audio_repeat = 0;
    g_cdrom_state.rec.io_state = 0x10;

    return 1;
}

s32 cdrom_StartAudioEntry(s32 entry_index) {
    Unk8008F13CRow *audio_entry = &g_cdrom_audio_entries[entry_index];
    if (cdrom_StartAudio(cdrom_GetFileIndex(5, audio_entry->unk_0),
                         audio_entry->unk_1) != 0) {
        if (audio_entry->unk_4 != -1) {
            g_cdrom_state.rec.audio_end_pos =
                CdPosToInt(&g_cd_file_table[g_cdrom_state.rec.file_index].loc) +
                audio_entry->unk_4;
        }
        return 1;
    }
    return 0;
}

s32 cdrom_StartAudioEntryHeld(void) {
    s32 ret = ((s32(*)())cdrom_StartAudioEntry)();
    if (ret) {
        g_cdrom_state.rec.audio_hold = 1;
        return 1;
    }
    return 0;
}

void cdrom_SetAudioRepeat(s16 arg0) { g_cdrom_state.rec.audio_repeat = arg0; }

s32 cdrom_StartAudioHeld(void) {
    if (((s32(*)())cdrom_StartAudio)() != 0) {
        g_cdrom_state.rec.audio_hold = 1;
        return 1;
    }
    return 0;
}

void cdrom_RequestStop(void) {
    g_cdrom_state.rec.audio_hold = 0;
    g_cdrom_state.rec.stop_request = 1;
}

void cdrom_ReleaseAudio(void) { g_cdrom_state.rec.audio_hold = 0; }

void cdrom_WaitAudioStarted(void) {
    while (g_cdrom_state.rec.io_state != 0x16) {
        comb_ExchangeEmptyPad();
        cdrom_Update();
        VSync(2);
    }
}

void cdrom_PauseAndWait(void) {
    if (g_cdrom_state.rec.io_state != 0) {
        cdrom_Pause();
    }
    cdrom_WaitIdle();
}

s32 cdrom_ReadWait(s32 nbytes, s32 buf, s32 mode) {
    s32 v = nbytes;
    nbytes += 0x7FF;
    if (nbytes < 0) {
        nbytes = v + 0xFFE;
    }
    CdRead(nbytes >> 11, buf, mode);
    do {
        v = CdReadSync(1, 0);
        if (v > 0) {
            VSync(0);
        }
    } while (v > 0);
    return v;
}

/* Loads a PS-EXE from disc: seeks to entry g_cdrom_file_group_bases[6] (=156,
 * MOVOVL.EXE) of g_cd_file_table, reads one sector, copies the struct EXEC at
 * +0x10 into *dest, then reads dest->t_size bytes from the next sector to
 * dest->t_addr. Any failed read restarts from the seek. The sole caller is
 * sys_Exec. */
void cdrom_LoadExec(EXEC *dest) {
    u8 header_sector[0x800];
    CdlLOC next_sector_loc;
    s32 file_index;
    s32 read_result;
    s32 pos;
    s32 mode;

    mode = 0x80; /* CdlModeSpeed - double-speed transfer */
    file_index = cdrom_GetFileIndex(6, 0);

    for (;;) {
        CdControl(2, (u8 *)&g_cd_file_table[file_index].loc, 0);
        read_result = cdrom_ReadWait(0x800, (s32)header_sector, mode);
        if (read_result != 0)
            continue;

        *dest = *(EXEC *)&header_sector[0x10];

        pos = CdPosToInt(&g_cd_file_table[file_index].loc);
        CdIntToPos(pos + 1, &next_sector_loc);
        CdControl(2, (u8 *)&next_sector_loc, 0);
        read_result = cdrom_ReadWait(dest->t_size, dest->t_addr, mode);
        if (read_result == 0)
            break;
    }
}

void sys_Exec(s32 argc, s32 *argv, s32 stack_addr) {
    EXEC exec;
    VSync(0);
    SetDispMask(0);
    gpu_ResetGraphMode1();
    snd_Quit();
    memcard_Quit();
    ResetCallback();
    CdInit();
    cdrom_LoadExec(&exec);
    DrawSync(0);
    ResetGraph(0);
    StopPAD();
    StopCallback();
    exec.s_addr = stack_addr;
    exec.s_size = 0;
    EnterCriticalSection();
    Exec(&exec, argc, argv);
    sys_Init();
    snd_InitAndLoadCommonVab();
    VSync(0);
    SetDispMask(1);
}

void sys_ExecMovieOverlay(
    s32 a0, s32 a1, s32 file_index_offset, s32 a3, s32 a4) {
    /* FAKE: frame layout. The target's 0x48 frame implies a larger argv
       buffer than the 24 bytes ever written (s32 [7] and [8] are
       byte-identical; sp[6], the bytes written: score 15); oversized-locals
       carve-out (dead-vars-local-array), owner ruling 2026-07-13. */
    s32 sp[8];
    s32 v0;

    v0 = cdrom_GetFileIndex(6, file_index_offset);
    sp[0] = (s32)&g_cd_file_table[v0];
    sp[1] = a3;
    sp[2] = a0;
    sp[3] = a1;
    v0 = cdrom_GetFileIndex(6, 2);
    sp[4] = (s32)&g_cd_file_table[v0];
    sp[5] = a4;
    v0 = (s32)GetSharedBuffer();
    sys_Exec(6, sp, v0 + 0x7FC);
}

