#!/usr/bin/env python3
"""Render docs/naming/suspect-list.md — the SUSPECT slice of the naming census.

Read-only apart from its one output file. Run after docs/naming/build_census.py.
"""
import csv, io, os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSVP = os.path.join(ROOT, "docs", "naming", "function-names.csv")
OUTP = os.path.join(ROOT, "docs", "naming", "suspect-list.md")

with io.open(CSVP, encoding="utf-8", newline="") as fh:
    rows = list(csv.DictReader(fh))
sus = [r for r in rows if r["tier"] == "SUSPECT"]

AUTOPAT = re.compile(r"(func|D)_[0-9A-Fa-f]{8}")
GROUPS = collections.OrderedDict([
    ("Recorded contradiction (MISNAMED / MISNOMERS.md)", lambda r: r["origin"].startswith("misname")),
    ("PS2-only symbol family (tsl* / su* / Vu0* / Vu1*)", lambda r: "ps2-only" in r["origin"]),
    ("Kengo-derived provenance", lambda r: r["origin"].startswith("kengo")),
    ("Other", lambda r: True),
])

live_glabel = sum(1 for r in sus if not AUTOPAT.fullmatch(r["glabel"]))
out = [
    "# SUSPECT names — the reset set\n",
    "Auto-generated by `docs/naming/build_suspect_list.py`; do not hand-edit. Rows are the "
    "`tier == SUSPECT` slice of [`function-names.csv`](function-names.csv), which carries the "
    "full evidence string for every function.\n",
    f"**{len(sus)} SUSPECT** — {sum(1 for r in sus if r['action'] == 'RESET')} recommended RESET, "
    f"{sum(1 for r in sus if r['action'] == 'RENAME')} RENAME. "
    f"{sum(1 for r in sus if r['queued'] == 'yes')} are still on `engine/queue.json`; "
    f"{live_glabel} have a live `glabel` — for those a reset must also move the `.s` filename "
    "and the `INCLUDE_ASM` argument, or the linker gets an undefined symbol.\n",
    "See [README.md](README.md) for the tier definitions, the owner directive, and the "
    "rename-cascade warning that governs how a reset wave may be applied.\n",
]

seen = set()
for title, pred in GROUPS.items():
    g = [r for r in sus if r["address"] not in seen and pred(r)]
    for r in g:
        seen.add(r["address"])
    if not g:
        continue
    g.sort(key=lambda r: -int(r["insns"]))
    out.append(f"\n## {title} — {len(g)}\n")
    out.append("| Address | Name | Insns | Action | Evidence |")
    out.append("|---|---|---:|---|---|")
    for r in g:
        e = r["evidence"].replace("|", r"\|").replace("\n", " ")
        if len(e) > 430:
            e = e[:430].rsplit(" ", 1)[0] + " …"
        act = (f"**{r['action']}** → `{r['proposed_name']}`"
               if r["action"] == "RENAME" else r["action"])
        out.append(f"| `{r['address']}` | `{r['current_name']}` | {r['insns']} | {act} | {e} |")

io.open(OUTP, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"wrote {OUTP}: {len(sus)} SUSPECT rows across {len(GROUPS)} groups")
