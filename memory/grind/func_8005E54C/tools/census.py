#!/usr/bin/env python3
"""Frame census of asm/funcs/func_8005E54C.s: every $sp-relative instruction (address, opcode, offset)."""
import re
out = ['# func_8005E54C target frame census (from asm/funcs/func_8005E54C.s; generated by tools/census.py)',
       '# frame 0xB8: 0x00-0x17 outgoing args (0x10 = SetDrawMode 5th arg), locals 0x18-0x5F,',
       '# spill slots 0x60-0x8F (arg0 0x60, arg1 0x68, arg2 0x70, ft4 0x78, mode_off 0x80, end_off 0x88),',
       '# saves 0x90-0xB4. Region under test: 0x54-0x5F (0x58-0x5F = the 8-aligned slot after s).',
       '']
rows = []
for n, line in enumerate(open('asm/funcs/func_8005E54C.s'), 1):
    m = re.search(r'/\* \w+ (8005[0-9A-F]+) \w+ \*/\s+(\S+)\s+(.*)$', line)
    if not m or '$sp' not in m.group(3):
        continue
    addr, op, ops = m.groups()
    off = re.search(r'(-?0x[0-9A-Fa-f]+|\d+)\(\$sp\)', ops)
    imm = re.search(r'\$sp, (-?0x[0-9A-Fa-f]+)$', ops)
    o = int((off or imm).group(1), 16) if (off or imm) else None
    kind = 'mem' if off else ('addr' if imm else 'other')
    rows.append((addr, op, ops.strip(), o, kind, n))
    out.append('%s  line %4d  %-6s %-24s offset %s (%s)' % (addr, n, op, ops.strip(),
               hex(o) if o is not None else '-', kind))
hit = [r for r in rows if r[4] == 'mem' and r[3] is not None and 0x54 <= r[3] <= 0x5F]
addrs = sorted(set(hex(r[3]) for r in rows if r[4] == 'addr'))
out += ['', 'memory operands in 0x54..0x5F: %d' % len(hit),
        'address formations sp+K: %s (0xB8 = the epilogue sp restore)' % ', '.join(addrs),
        'bases derived from sp+0x18/0x1A reach vals (0x18..0x1B, index 0..1) and wins via +8 (0x20..0x23);',
        'sp+0x28 (&s) is passed to func_8007352C / func_80073728, which read descriptor offsets 0x00..0x2B only',
        '(asm/funcs/func_8007352C.s: 0x0..0x2B($s4); asm/funcs/func_80073728.s: 0x0..0x2B($s2)), i.e. sp+0x28..0x53.']
open('memory/grind/func_8005E54C/frame_census.txt', 'w', newline='\n').write('\n'.join(out) + '\n')
print('\n'.join(out[-6:]))
